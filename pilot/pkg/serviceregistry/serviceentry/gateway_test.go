var backendCreationTime = time.Date(2024, 1, 2, 3, 4, 5, 0, time.UTC)

func xbackendConfig(name string, spec *gatewayx.BackendSpec) config.Config {
	return config.Config{
		Meta: config.Meta{
			GroupVersionKind:  gvk.XBackend,
			Name:              name,
			Namespace:         "default",
			CreationTimestamp: backendCreationTime,
		},
		Spec: spec,
	}
}

func externalHostnameSpec(hostname string, port int32) *gatewayx.BackendSpec {
	return &gatewayx.BackendSpec{
		Type: gatewayx.BackendTypeExternalHostname,
		ExternalHostname: &gatewayx.ExternalHostnameBackend{
			Hostname: gatewayv1.PreciseHostname(hostname),
		},
		Port: gatewayx.BackendPort{Port: gatewayx.PortNumber(port)},
	}
}

func TestBackendToServiceEntry(t *testing.T) {
	httpProtocol := gatewayx.BackendProtocolHTTP
	tcpProtocol := gatewayx.BackendProtocolTCP

	specWithProtocol := func(hostname string, port int32, p *gatewayx.BackendProtocol) *gatewayx.BackendSpec {
		s := externalHostnameSpec(hostname, port)
		s.Protocol = p
		return s
	}

	cases := []struct {
		name         string
		domainSuffix string
		in           config.Config
		want         *networking.ServiceEntry
		wantName     string
	}{
		{
			name: "explicit protocol",
			in:   xbackendConfig("explicit", specWithProtocol("example.com", 443, &httpProtocol)),
			want: &networking.ServiceEntry{
				Hosts:      []string{"example.com"},
				Ports:      []*networking.ServicePort{{Number: 443, Protocol: "HTTP", Name: "HTTP"}},
				Location:   networking.ServiceEntry_MESH_EXTERNAL,
				Resolution: networking.ServiceEntry_DNS,
			},
			wantName: "explicit~istio-autogenerated-k8s-gateway",
		},
		{
			name: "unset protocol defaults to HTTP",
			in:   xbackendConfig("defaulted", externalHostnameSpec("example.com", 80)),
			want: &networking.ServiceEntry{
				Hosts:      []string{"example.com"},
				Ports:      []*networking.ServicePort{{Number: 80, Protocol: "HTTP", Name: "HTTP"}},
				Location:   networking.ServiceEntry_MESH_EXTERNAL,
				Resolution: networking.ServiceEntry_DNS,
			},
			wantName: "defaulted~istio-autogenerated-k8s-gateway",
		},
		{
			name: "explicit TCP is preserved",
			in:   xbackendConfig("tcp", specWithProtocol("example.com", 9000, &tcpProtocol)),
			want: &networking.ServiceEntry{
				Hosts:      []string{"example.com"},
				Ports:      []*networking.ServicePort{{Number: 9000, Protocol: "TCP", Name: "TCP"}},
				Location:   networking.ServiceEntry_MESH_EXTERNAL,
				Resolution: networking.ServiceEntry_DNS,
			},
			wantName: "tcp~istio-autogenerated-k8s-gateway",
		},
		{
			name: "wrong spec type is ignored",
			in: config.Config{
				Meta: config.Meta{GroupVersionKind: gvk.XBackend, Name: "bad", Namespace: "default"},
				Spec: &gatewayx.XBackend{},
			},
		},
		{
			name: "nil externalHostname is ignored",
			in: xbackendConfig("no-hostname", &gatewayx.BackendSpec{
				Type: gatewayx.BackendTypeExternalHostname,
				Port: gatewayx.BackendPort{Port: 80},
			}),
		},
		{
			name: "cluster-local hostname is rejected",
			in:   xbackendConfig("local", externalHostnameSpec("productpage.prod.svc.cluster.local", 80)),
		},
		{
			name:         "custom domain suffix is rejected",
			domainSuffix: "mesh.local",
			in:           xbackendConfig("custom", externalHostnameSpec("productpage.prod.svc.mesh.local", 80)),
		},
		{
			name:         "unrelated hostname is allowed under a custom domain suffix",
			domainSuffix: "mesh.local",
			in:           xbackendConfig("other", externalHostnameSpec("productpage.prod.svc.other.local", 80)),
			want: &networking.ServiceEntry{
				Hosts:      []string{"productpage.prod.svc.other.local"},
				Ports:      []*networking.ServicePort{{Number: 80, Protocol: "HTTP", Name: "HTTP"}},
				Location:   networking.ServiceEntry_MESH_EXTERNAL,
				Resolution: networking.ServiceEntry_DNS,
			},
			wantName: "other~istio-autogenerated-k8s-gateway",
		},
		{
			name: "multicluster services hostname is rejected",
			in:   xbackendConfig("mcs", externalHostnameSpec("productpage.prod.svc.clusterset.local", 80)),
		},
	}

	for _, tt := range cases {
		t.Run(tt.name, func(t *testing.T) {
			suffix := tt.domainSuffix
			if suffix == "" {
				suffix = "cluster.local"
			}
			got := backendToServiceEntry(suffix)(nil, tt.in)
			if tt.want == nil {
				if got != nil {
					t.Fatalf("expected no ServiceEntry, got %v", got)
				}
				return
			}
			if got == nil {
				t.Fatal("expected a ServiceEntry, got nil")
			}
			if got.GroupVersionKind != gvk.ServiceEntry {
				t.Errorf("unexpected GroupVersionKind: %v", got.GroupVersionKind)
			}
			if got.Name != tt.wantName {
				t.Errorf("name: got %q, want %q", got.Name, tt.wantName)
			}
			if got.Namespace != tt.in.Namespace {
				t.Errorf("namespace: got %q, want %q", got.Namespace, tt.in.Namespace)
			}
			// The creation timestamp decides which config wins a same-hostname conflict, so it
			// must be inherited rather than left at the zero time.
			if !got.CreationTimestamp.Equal(tt.in.CreationTimestamp) {
				t.Errorf("creationTimestamp: got %v, want %v", got.CreationTimestamp, tt.in.CreationTimestamp)
			}
			if diff := cmp.Diff(tt.want, got.Spec.(*networking.ServiceEntry), protocmp.Transform()); diff != "" {
				t.Errorf("unexpected ServiceEntry (-want +got):\n%s", diff)
			}
		})
	}
}

func TestBackendProtocolToServiceEntryProtocol(t *testing.T) {
	cases := map[gatewayx.BackendProtocol]string{
		gatewayx.BackendProtocolHTTP:   "HTTP",
		gatewayx.BackendProtocolHTTP11: "HTTP",
		gatewayx.BackendProtocolHTTP2:  "HTTP2",
		gatewayx.BackendProtocolH2C:    "HTTP2",
		gatewayx.BackendProtocolGRPC:   "GRPC",
		// MCP is carried over HTTP; ServicePort has no MCP protocol of its own.
		gatewayx.BackendProtocolMCP: "HTTP",
		gatewayx.BackendProtocolTCP: "TCP",
		"SomethingElse":             "TCP",
	}
	for in, want := range cases {
		t.Run(string(in), func(t *testing.T) {
			if got := backendProtocolToServiceEntryProtocol(in); got != want {
				t.Errorf("got %q, want %q", got, want)
			}
		})
	}
}

// The synthetic name must not be expressible as a Kubernetes object name, so that it can never
// collide with a user-authored ServiceEntry in the same namespace.
func TestBackendServiceEntryNameCannotCollide(t *testing.T) {
	got := backendToServiceEntry("cluster.local")(nil, xbackendConfig("collide", externalHostnameSpec("example.com", 80)))
	if got == nil {
		t.Fatal("expected a ServiceEntry")
	}
	if errs := validation.IsDNS1123Subdomain(got.Name); len(errs) == 0 {
		t.Errorf("name %q is a valid Kubernetes object name and could collide with a user ServiceEntry", got.Name)
	}
}
